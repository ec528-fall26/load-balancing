"""Generate the frontend's policy labels/types from the Python registry.

Run with uv run python scripts/generate_policy_metadata.py [--check].
"""
import argparse
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from lbsim.policies import policy_options


def render():
    lines = ['// Generated by scripts/generate_policy_metadata.py; edit lbsim/policies.py.']
    for topology, name in [('single_pool', 'serverPolicies'), ('regions', 'regionalPolicies')]:
        lines.append(f'export const {name} = '+json.dumps(policy_options(topology), indent=2)+' as const;')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'frontend/lib/policy-metadata.ts'
    expected = render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            parser.exit(1, 'Policy metadata is stale; run uv run python scripts/generate_policy_metadata.py\n')
    else:
        target.write_text(expected)
